import hashlib
import os
import re
import struct
import sys

from rng_reference import Ref

HERE = os.path.dirname(os.path.abspath(__file__))
PRINT_TAG, ROLL_TAG = b"QD4P fair 1 print", b"QD4P fair 1 roll"


def word_list():
    src = open(os.path.join(HERE, "../../qd4p/qd_fair.c"), encoding="utf-8").read()
    body = src[src.index("words[256] = {"):]
    body = body[:body.index("};")]
    return re.findall(r'"([a-z]+)"', body)


def fingerprint(key):
    return hashlib.sha256(PRINT_TAG + key).digest()[:6]


def action_state(key, n):
    h = hashlib.sha256(ROLL_TAG + key + struct.pack("<I", n)).digest()
    s = list(struct.unpack("<4I", h[:16]))
    if not any(s):
        s[0] = 0x9E3779B9
    return s


def generator(key, n):
    r = Ref(0)
    r.s = action_state(key, n)
    return r


KEYS = [bytes(range(16)), bytes([0xFF] * 16), bytes(16),
        hashlib.sha256(b"QD4P test key").digest()[:16]]
ACTIONS = [0, 1, 2, 17, 1000, 0xFFFFFFFF]


